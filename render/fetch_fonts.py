#!/usr/bin/env python3
"""Fetch the render service's fonts at image build time (stdlib only).

Reads fonts.json, downloads every font and licence file from the pinned upstream commit, checks each against its
sha256 (any mismatch or failed download exits 1, so the image build stops), and writes into --out:
  <file>.ttf ...        the fonts
  licences/<file>.txt   their licence texts (OFL-1.1 asks for the licence to travel with the fonts)
  fonts.css             one @font-face per file, served to the render page as /fonts.css

    python3 fetch_fonts.py --out /opt/fonts
    python3 fetch_fonts.py --out DIR --from DIR2    # use files already downloaded into DIR2 (still hash-checked)
    python3 fetch_fonts.py --out DIR --family Inter  # only these families (the app's own UI fonts; repeatable)

Font files are never committed to the repository; this script is the only way they arrive.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import sys
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
SAFE = set("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_.")


def load_manifest(path: str | None = None) -> dict:
    with open(path or os.path.join(HERE, "fonts.json"), encoding="utf-8") as f:
        return json.load(f)


def check_entry(e: dict) -> None:
    """Refuse a manifest entry that could write outside --out or inject into fonts.css."""
    if not e.get("file") or set(e["file"]) - SAFE or e["file"].startswith("."):
        raise ValueError(f"bad file name in fonts.json: {e.get('file')!r}")
    if len(e.get("sha256", "")) != 64:
        raise ValueError(f"missing sha256 for {e['file']}")
    if "family" in e and (not e["family"] or set(e["family"]) - SAFE - {" "}):
        raise ValueError(f"bad family name in fonts.json: {e.get('family')!r}")


def css(manifest: dict) -> str:
    out = ["/* Generated by fetch_fonts.py from fonts.json. Licences: licences/ next to this file. */"]
    for e in manifest["fonts"]:
        check_entry(e)
        out.append("@font-face{font-family:'%s';font-style:%s;font-weight:%s;font-display:block;src:url(/fonts/%s) "
                   "format('truetype')}" % (e["family"], "italic" if e["style"] == "italic" else "normal",
                                            e["weight"], e["file"]))
    return "\n".join(out) + "\n"


def _fetch(url: str) -> bytes:
    if urllib.parse.urlsplit(url).scheme != "https":
        raise ValueError(f"refusing a non-https font URL: {url}")
    req = urllib.request.Request(url, headers={"User-Agent": "media-lab-render-fonts/1"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", required=True)
    ap.add_argument("--from", dest="src", help="read files from this folder instead of downloading")
    ap.add_argument("--manifest")
    ap.add_argument("--family", action="append", help="only this family (repeatable); default: every family")
    a = ap.parse_args(argv)
    m = load_manifest(a.manifest)
    if a.family:
        unknown = set(a.family) - {e["family"] for e in m["fonts"]}
        if unknown:
            print(f"fetch_fonts: no such family in the manifest: {', '.join(sorted(unknown))}", file=sys.stderr)
            return 1
        m = dict(m, fonts=[e for e in m["fonts"] if e["family"] in a.family],
                 licences=[e for e in m["licences"] if e["family"] in a.family])
    os.makedirs(os.path.join(a.out, "licences"), exist_ok=True)
    bad = 0
    jobs = [(e, e["file"]) for e in m["fonts"]] + [(e, os.path.join("licences", e["file"])) for e in m["licences"]]
    for e, rel in jobs:
        check_entry(e)
        dest = os.path.join(a.out, rel)
        try:
            if a.src:
                with open(os.path.join(a.src, rel), "rb") as f:
                    data = f.read()
            else:
                data = _fetch(m["base"] + urllib.parse.quote(e["path"]))
        except (OSError, ValueError) as exc:
            print(f"fetch_fonts: {rel}: {exc}", file=sys.stderr)
            bad += 1
            continue
        got = hashlib.sha256(data).hexdigest()
        if got != e["sha256"]:
            print(f"fetch_fonts: {rel}: sha256 {got} does not match the pinned {e['sha256']}", file=sys.stderr)
            bad += 1
            continue
        with open(dest + ".part", "wb") as f:
            f.write(data)
        shutil.move(dest + ".part", dest)
    if bad:
        print(f"fetch_fonts: {bad} file(s) failed; nothing is usable until all pass", file=sys.stderr)
        return 1
    with open(os.path.join(a.out, "fonts.css"), "w", encoding="utf-8") as f:
        f.write(css(m))
    print(f"fetch_fonts: {len(m['fonts'])} fonts and {len(m['licences'])} licences verified into {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
